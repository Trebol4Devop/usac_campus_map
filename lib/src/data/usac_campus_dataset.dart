  static CampusBuilding? getById(String id) {
    try {
      return allBuildings.firstWhere((b) => b.id.toLowerCase() == id.toLowerCase());
    } catch (_) {
      return null;
    }
  }

  static List<CampusBuilding> getByCategory(BuildingCategory category) {
    return allBuildings.where((b) => b.category == category).toList(growable: false);
  }

  static List<CampusBuilding> search(String query) {
    if (query.trim().isEmpty) {
      return allBuildings;
    }
    final normalized = query.trim().toLowerCase();
    return allBuildings.where((b) {
      final matchesName = b.name.toLowerCase().contains(normalized);
      final matchesAcronym = b.acronym?.toLowerCase().contains(normalized) ?? false;
      final matchesDescription = b.description.toLowerCase().contains(normalized);
      final matchesId = b.id.toLowerCase().contains(normalized);
      return matchesName || matchesAcronym || matchesDescription || matchesId;
    }).toList(growable: false);
  }
